"""Build reports/BENCHMARK_ABLATIONS.md: what an easier benchmark would have let us claim.

    make ablations && python scripts/compare_ablations.py

Most digital-twin papers validate a twin against a simulator built from the twin's own equations,
on a schedule the model already knows. This script quantifies what that choice is worth, by running
the identical pipeline under four benchmarks and putting the numbers side by side:

  hard      the submitted setting: body runs truth_model.py, eating is messy
  matched   body runs the TWIN's own equations (no model misspecification)
  easy      tight meal schedule, almost no unplanned eating (calendar ~ oracle)
  both      matched + easy - roughly the setting a generous evaluation produces

The gap between `hard` and `both` is the honest cost of a benchmark that flatters the model.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from upvaas.config import REPORT_DIR  # noqa: E402

RUNS = [("_q_hard", "Hard (as submitted)"), ("_q_matched", "Matched model"),
        ("_q_easy", "Easy meals"), ("_q_both", "Matched + easy")]


def _f(v, nd=3):
    return "–" if v is None else f"{v:.{nd}f}"


def load(tag: str) -> dict | None:
    p = REPORT_DIR / f"metrics{tag}.json"
    return json.load(open(p)) if p.exists() else None


def main() -> int:
    runs = [(tag, lab, load(tag)) for tag, lab in RUNS]
    have = [(t, l, m) for t, l, m in runs if m]
    if len(have) < 2:
        sys.exit("Need at least two ablation runs. Run:  make ablations")
    n = have[0][2]["cohort"]["n_patients"]

    L = [f"# What an easier benchmark would have let us claim",
         "",
         "*Generated by `scripts/compare_ablations.py`. Every row is the identical pipeline and the identical",
         f"model, run over {n} synthetic patients under a different set of simulation assumptions. Nothing about",
         "the twin changes between rows — only how hard the test is.*",
         "",
         "## Why this file exists",
         "",
         "A digital twin validated against a simulator built from the twin's own equations measures parameter",
         "error, not the thing that breaks twins in clinic: the body doing something the model has no term for.",
         "Add a meal schedule the model already knows and the prediction task quietly becomes a timetable",
         "lookup. Both shortcuts are common, and both inflate results substantially. This table is how much.",
         "",
         "| Setting | Body model | Eating | plan↔reality carb r | Hypo AUPRC (tier A) | Hyper AUPRC (tier A) | Twin RMSE @120 min |",
         "|---|---|---|---|---|---|---|"]

    for tag, lab, m in have:
        bd = m.get("benchmark_difficulty", {})
        hy = m["models"]["A_full/full/hypo"]
        hp = m["models"]["A_full/full/hyper"]
        body = "**different**" if bd.get("model_mismatch") else "same as twin"
        meals = "**messy**" if bd.get("realistic_meals") else "near-oracle"
        bold = "**" if tag == "_q_hard" else ""
        L.append(f"| {bold}{lab}{bold} | {body} | {meals} | {_f(bd.get('plan_vs_logged_carb_corr_2h'), 2)} | "
                 f"{_f(hy.get('auprc'))} | {_f(hp.get('auprc'))} | "
                 f"{m['forecast']['120min']['twin_rmse']:.0f} mg/dL |")

    hard = dict(have)[RUNS[0][0]] if RUNS[0][0] in dict((t, m) for t, _, m in have) else have[0][2]
    both = next((m for t, _, m in have if t == "_q_both"), None)
    L.append("")
    if both:
        h_hy = hard["models"]["A_full/full/hypo"]["auprc"]
        b_hy = both["models"]["A_full/full/hypo"]["auprc"]
        h_hp = hard["models"]["A_full/full/hyper"]["auprc"]
        b_hp = both["models"]["A_full/full/hyper"]["auprc"]
        h_r = hard["forecast"]["120min"]["twin_rmse"]
        b_r = both["forecast"]["120min"]["twin_rmse"]
        L += ["## The cost of a generous benchmark", "",
              f"Running the same twin against its own equations on a predictable meal schedule would have let us",
              f"report **hypoglycaemia AUPRC {b_hy:.3f} instead of {h_hy:.3f}** "
              f"({b_hy / max(h_hy, 1e-9):.1f}× higher), **hyperglycaemia AUPRC {b_hp:.3f} instead of "
              f"{h_hp:.3f}**, and a **2-hour forecast RMSE of {b_r:.0f} mg/dL instead of {h_r:.0f}**.",
              "",
              f"A 2-hour glucose forecast error of {b_r:.0f} mg/dL would be well ahead of the published state of the",
              "art, which is roughly 30–40 mg/dL. That is the tell: when a simulation study reports forecast",
              "errors far below what anyone achieves on real CGM data, the simulator is usually the reason.",
              "",
              "We report the hard numbers in the README and keep this file so the difference is auditable.",
              ""]
    L += ["## Reproducing this table", "", "```bash", "make ablations                      # runs all four settings",
          "python scripts/compare_ablations.py  # regenerates this file", "```", "",
          "Each run writes its own `reports/metrics_*.json`, so every number above can be traced to a file.",
          ""]

    out = REPORT_DIR / "BENCHMARK_ABLATIONS.md"
    out.write_text("\n".join(L))
    print(f"wrote {out.relative_to(ROOT)}  ({len(have)} of {len(RUNS)} settings present)")
    for _, lab, m in have:
        hy = m["models"]["A_full/full/hypo"]
        print(f"  {lab:<22} hypo AUPRC {hy['auprc']:.3f}   RMSE@120 {m['forecast']['120min']['twin_rmse']:.0f} mg/dL")
    return 0


if __name__ == "__main__":
    sys.exit(main())
